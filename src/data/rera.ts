export function builderStats(slug: string): BuilderStats {
  const list = projectsByBuilder(slug);
  const completed = list.filter((p) => p.status === "Completed").length;
  const ongoing = list.filter((p) => p.status === "Under Construction").length;
  const launches = list.filter((p) => p.status === "New Launch").length;
  const lapsed = list.filter((p) => p.status === "Lapsed").length;
  const complaints = list.reduce((s, p) => s + p.complaints, 0);
  const avgBookedPct = list.length
    ? Math.round(list.reduce((s, p) => s + p.bookedPct, 0) / list.length)
    : 0;
  return { total: list.length, completed, ongoing, launches, lapsed, complaints, avgBookedPct };
}

/** Unified search across projects and builders. */
export type SearchResult =
  | { kind: "project"; item: ReraProject; score: number }
  | { kind: "builder"; item: Builder; score: number };

export function searchAll(query: string): SearchResult[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];

  const results: SearchResult[] = [];

  for (const p of PROJECTS) {
    let score = 0;
    if (p.rera.toLowerCase() === q) score = 100;
    else if (p.rera.toLowerCase().includes(q)) score = 80;
    else if (p.name.toLowerCase().startsWith(q)) score = 70;
    else if (p.name.toLowerCase().includes(q)) score = 55;
    else if (p.locality.toLowerCase().includes(q)) score = 40;
    else if (p.builder.toLowerCase().includes(q)) score = 45;
    else if (p.region.toLowerCase().includes(q)) score = 30;
    if (score > 0) results.push({ kind: "project", item: p, score });
  }

  for (const b of BUILDERS) {
    let score = 0;
    if (b.name.toLowerCase().startsWith(q)) score = 75;
    else if (b.name.toLowerCase().includes(q)) score = 60;
    else if (b.slug.includes(q)) score = 50;
    if (score > 0) results.push({ kind: "builder", item: b, score });
  }

  return results.sort((a, b) => b.score - a.score).slice(0, 24);
}

/** Aggregate platform statistics for the landing page. */
export function platformStats() {
  const totalUnits = PROJECTS.reduce((s, p) => s + p.totalUnits, 0);
  const completed = PROJECTS.filter((p) => p.status === "Completed").length;
  const ongoing = PROJECTS.filter((p) => p.status === "Under Construction").length;
  const cities = new Set(PROJECTS.map((p) => p.city)).size;
  const investmentTracked = PROJECTS.reduce(
    (s, p) => s + p.financials.estimatedCostCr,
    0
  );
  return {
    projects: PROJECTS.length,
    builders: BUILDERS.length,
    units: totalUnits,
    completed,
    ongoing,
    cities,
    investmentCr: investmentTracked,
  };
}
