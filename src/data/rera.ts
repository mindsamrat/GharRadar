export type ProjectStatus =
  | "Completed"
  | "Under Construction"
  | "New Launch"
  | "Lapsed"
  | "Registered";

export type PropertyType =
  | "Residential"
  | "Commercial"
  | "Mixed-use"
  | "Plotted"
  | "Villa";

export type City = "Mumbai" | "Pune";

export interface ReraProject {
  rera: string;
  name: string;
  builder: string;
  builderSlug: string;
  city: City;
  locality: string;
  region: string;
  lat: number;
  lng: number;
  status: ProjectStatus;
  propertyType: PropertyType;
  registeredOn: string; // ISO date
  proposedCompletion: string; // ISO date (RERA declared)
  completedOn?: string; // ISO date (OC / completion)
  configs: string[];
  carpetAreaMin: number; // sq.ft
  carpetAreaMax: number; // sq.ft
  priceMin: number; // total ₹
  priceMax: number; // total ₹
  pricePerSqft: number;
  towers: number;
  totalUnits: number;
  bookedPct: number;
  landAreaAcres: number;
  amenities: string[];
  complaints: number;
  reraExtended: boolean;
  litigation: boolean;
  bankApproved: string[];
  financials: { receivedCr: number; estimatedCostCr: number };
}

